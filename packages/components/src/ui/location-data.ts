/**
 * Static location dataset for LocationPicker: countries, regions
 * (states/provinces), and localities (LGAs). Resolved dynamically by
 * country -> region -> locality in the picker. See location-picker.tsx.
 */

export interface Country {
  /** ISO alpha-2 country code. */
  code: string;
  name: string;
}

export interface Region {
  /** Region/state id within the country. */
  id: string;
  name: string;
}

export interface Locality {
  /** Locality/LGA id within the region. */
  id: string;
  name: string;
}

/**
 * The term each country uses for its first-level division (what the
 * "state" select shows). Falls back to "region".
 */
export const REGION_LABELS: Record<string, string> = {
  NG: "state",
  US: "state",
  IN: "state",
  BR: "state",
  MX: "state",
  AU: "state",
  KE: "county",
  IE: "county",
  GB: "country",
  GH: "region",
  TZ: "region",
  ET: "region",
  UG: "region",
  RW: "province",
  ZA: "province",
  CN: "province",
  EG: "governorate",
  SA: "region",
  AE: "emirate",
  CA: "province",
  JP: "prefecture",
};

/**
 * The term each country uses for its second-level division (what the
 * "LGA/locality" select shows). Falls back to "locality".
 */
export const LOCALITY_LABELS: Record<string, string> = {
  NG: "LGA",
  US: "county",
  KE: "sub-county",
  GB: "district",
  GH: "district",
  IN: "district",
  CN: "county",
  BR: "municipality",
  JP: "municipality",
};

/** Resolve the region term for a country (e.g. "NG" -> "state"). */
export function getRegionLabel(country?: string): string {
  return (country && REGION_LABELS[country]) || "region";
}

/** Resolve the locality term for a country (e.g. "NG" -> "LGA"). */
export function getLocalityLabel(country?: string): string {
  return (country && LOCALITY_LABELS[country]) || "locality";
}

