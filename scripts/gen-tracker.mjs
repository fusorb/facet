#!/usr/bin/env node
/**
 * Tracker sync: regenerate the ground-truth STATE block in `.agent/output.txt`
 * from repository state (git + package.json + ci-cd.yml + the component
 * inventory), so the dashboard can never lie about HEAD, versions, or the gate
 * list.
 *
 * Run it before a commit, or after each completed milestone:
 *
 *   node scripts/gen-tracker.mjs      # or: pnpm sync:tracker
 *
 * The block between the `<!-- STATE:BEGIN -->` / `<!-- STATE:END -->` markers is
 * rewritten in place; the hand-written narrative below it is preserved. A
 * machine-readable copy is written to `.agent/state.json`.
 *
 * `.agent/` is local-only (gitignored except episodes.md) by design, so this
 * script is the thing that is committed; its output is per-checkout.
 */
import fs from "node:fs";
import path from "node:path";
import { execSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const AGENT = path.join(root, ".agent");
const OUT = path.join(AGENT, "output.txt");
const STATE_JSON = path.join(AGENT, "state.json");
const BEGIN = "<!-- STATE:BEGIN";
const END = "<!-- STATE:END -->";

function run(cmd) {
  try {
    return execSync(cmd, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return "";
  }
}

function readJson(p) {
  try {
    return JSON.parse(fs.readFileSync(p, "utf8"));
  } catch {
    return null;
  }
}

// --- git -------------------------------------------------------------------
const headHash = run("git rev-parse --short HEAD");
const headDate = run("git show -s --format=%cs HEAD");
const headSubject = run("git show -s --format=%s HEAD");
const branch = run("git rev-parse --abbrev-ref HEAD") || "(detached)";
const counts = run("git rev-list --left-right --count origin/main...HEAD"); // "behind\tahead"
let behind = "?", ahead = "?";
if (counts) {
  const [b, a] = counts.split(/\s+/);
  behind = b;
  ahead = a;
}
const treeClean = run("git status --porcelain --untracked-files=all").length === 0;

// --- packages --------------------------------------------------------------
const pkgRoot = path.join(root, "packages");
const versions = [];
let privateCount = 0;
for (const dir of fs.existsSync(pkgRoot) ? fs.readdirSync(pkgRoot) : []) {
  const pj = readJson(path.join(pkgRoot, dir, "package.json"));
  if (!pj) continue;
  if (pj.private) privateCount += 1;
  versions.push({ name: pj.name, version: pj.version, private: Boolean(pj.private) });
}
versions.sort((a, b) => a.name.localeCompare(b.name));
const versionLine = versions
  .map((v) => `${v.name.replace("@fusorb/facet-", "")} ${v.version}${v.private ? " (private)" : ""}`)
  .join(", ");

// --- gates -----------------------------------------------------------------
const rootPkg = readJson(path.join(root, "package.json")) || { scripts: {} };
const checkAll = (rootPkg.scripts["check:all"] || "")
  .split("&&")
  .map((s) => s.trim().replace(/^pnpm\s+/, ""))
  .filter(Boolean);

let ciSteps = [];
try {
  const yml = fs.readFileSync(path.join(root, ".github", "workflows", "ci-cd.yml"), "utf8");
  // Only the `ci` job: everything before the changeset job's comment banner.
  const ciSection = yml.split(/# Auto-open the "Version Packages"/)[0];
  ciSteps = [...ciSection.matchAll(/- run: pnpm (.+)/g)].map((m) => m[1].trim().replace(/^-r\s+/, ""));
} catch {
  /* no workflow */
}

// --- inventory -------------------------------------------------------------
const uiDir = path.join(root, "packages", "components", "src", "ui");
const components = fs.existsSync(uiDir)
  ? fs.readdirSync(uiDir).filter(
      (f) => f.endsWith(".tsx") && !f.endsWith(".test.tsx") && !f.endsWith(".examples.tsx"),
    ).length
  : 0;

let testClaim = "";
try {
  const claude = fs.readFileSync(path.join(root, "CLAUDE.md"), "utf8");
  const m = claude.match(/(\d+)\s+tests across\s+(\d+)\s+files/);
  if (m) testClaim = `${m[1]} tests / ${m[2]} files (CLAUDE.md claim, not re-run)`;
} catch {
  /* no CLAUDE.md */
}

const ciExtra = ciSteps.filter((s) => !checkAll.includes(s));

// --- block -----------------------------------------------------------------
const block = [
  `${BEGIN} (regenerated by \`node scripts/gen-tracker.mjs\` — do not hand-edit) -->`,
  `**HEAD**: \`${headHash}\` — ${headDate} — *${headSubject}*`,
  `**Branch**: \`${branch}\` (ahead of origin/main by ${ahead}, behind ${behind}). **Working tree**: ${treeClean ? "clean" : "dirty"}.`,
  `**Gates**: \`check:all\` = ${checkAll.length} steps; CI \`ci\` job = ${ciSteps.length} steps.`,
  ciExtra.length
    ? `**CI-only (not in check:all)**: ${ciExtra.join(", ")}.`
    : `**CI-only (not in check:all)**: none.`,
  `**Counts**: ${components} components, ${versions.length} packages (${privateCount} private).`,
  `**Versions**: ${versionLine}`,
  testClaim ? `**Tests**: ${testClaim}.` : `**Tests**: (not found).`,
  `*Generated ${new Date().toISOString()}.*`,
  END,
].join("\n");

// --- write -----------------------------------------------------------------
fs.mkdirSync(AGENT, { recursive: true });
let doc = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "# facet — Status Dashboard\n";
if (doc.includes(BEGIN) && doc.includes(END)) {
  const start = doc.indexOf(BEGIN);
  const end = doc.indexOf(END) + END.length;
  doc = doc.slice(0, start) + block + doc.slice(end);
} else {
  doc = `# facet — Status Dashboard\n\n${block}\n${doc.replace(/^# facet — Status Dashboard\n?/, "")}`;
}
fs.writeFileSync(OUT, doc, "utf8");

fs.writeFileSync(
  STATE_JSON,
  JSON.stringify(
    {
      head: headHash,
      date: headDate,
      subject: headSubject,
      branch,
      ahead: Number(ahead) || 0,
      behind: Number(behind) || 0,
      treeClean,
      checkAll,
      ciSteps,
      versions,
      components,
    },
    null,
    2,
  ) + "\n",
  "utf8",
);

console.log("gen-tracker: refreshed .agent/output.txt STATE block");
console.log(`  HEAD ${headHash} on ${branch} (ahead ${ahead}, behind ${behind}), tree ${treeClean ? "clean" : "DIRTY"}`);
console.log(`  gates: check:all ${checkAll.length} / CI ${ciSteps.length}${ciExtra.length ? ` (CI-only: ${ciExtra.join(", ")})` : ""}`);
console.log(`  .agent/state.json written`);
